/// The demo repository with real pixels and a controllable location.
///
/// Extends rather than reimplements: [ChatRepository] is twenty members wide
/// and only two of them decide which way an attachment is fetched, so a
/// subclass keeps a test about that fork rather than about the other eighteen.
/// Shared between the bubble, the viewer and the golden suites because they all
/// need the same answers — demo mode's own `attachmentBytes` returns null, which
/// renders every photo as the broken-image placeholder.
class StubChatRepository extends DemoChatRepository {
  StubChatRepository({this.location, this.bytes, this.history, this.uploads})
    : super(uploadTick: Duration.zero);

  /// Non-null stands for an unencrypted room, which is the branch that goes
  /// through the download transport.
  final AttachmentLocation? location;

  /// What `downloadAndDecryptAttachment` would hand back. Null is an
  /// undecryptable or missing attachment.
  final Uint8List? bytes;

  /// Replaces the demo fixtures' synthesised back-and-forth.
  ///
  /// The chat itself still comes from the demo inbox, so the title, the
  /// network and the composer are the real ones; only *which messages are in
  /// the room* is under the test's control. Null leaves the fixtures alone.
  final List<WeftMessage>? history;

  /// Uploads the timeline should draw as in flight.
  ///
  /// Stated rather than driven, because a golden of a progress bar wants one
  /// exact percentage: running the demo transport would pin the image to
  /// however many ticks happened to have elapsed when the frame was captured.
  final List<UploadTask>? uploads;

  int locationCalls = 0;
  int byteCalls = 0;

  /// The last value [attachmentBytes] was called with, so a test can assert a
  /// full-size fetch was asked for rather than a 96-pixel crop.
  bool? lastThumbnail;

  /// The stated history, for every room.
  ///
  /// Overridden as well as [timelineFor] because a repository that replaced one
  /// and not the other would disagree with itself: `timelineFor` hands the
  /// screen one set of messages while every target lookup — a reply, a
  /// reaction, a thread send — walks the demo fixtures and finds nothing.
  @override
  List<WeftMessage> historyFor(ChatSource source, String title) =>
      history ?? super.historyFor(source, title);

  @override
  Future<MergedTimeline> timelineFor(String chatId) async {
    final replacement = history;
    if (replacement == null) return super.timelineFor(chatId);
    return MergedTimeline(
      sources: [
        InMemoryTimelineSource(
          roomId: chatId,
          network: ChatNetwork.matrix,
          pageSize: replacement.length,
          history: replacement,
        ),
      ],
    );
  }

  @override
  Stream<List<UploadTask>> watchUploads(String chatId) {
    final stated = uploads;
    return stated == null ? super.watchUploads(chatId) : Stream.value(stated);
  }

  @override
  Future<AttachmentLocation?> attachmentLocation(
    String roomId,
    String eventId,
  ) async {
    locationCalls++;
    return location;
  }

  @override
  Future<Uint8List?> attachmentBytes(
    String roomId,
    String eventId, {
    bool thumbnail = true,
  }) async {
    byteCalls++;
    lastThumbnail = thumbnail;
    return bytes;
  }
}
