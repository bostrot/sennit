#!/usr/bin/env python3
"""Writes the Android Firebase resources from a google-services.json.

What the Google Services Gradle plugin would generate, without the plugin:
Firebase's own content provider reads these values at process start, which is
what lets an FCM poke wake Sennit when it is not running. The JSON is not in
the repository; CI passes it in the GOOGLE_SERVICES_JSON secret, and a build
without it simply has no FCM (UnifiedPush and the built-in connection still
work). See docs/ops/push-gateway.md.

    python3 tooling/scripts/firebase_android_config.py google-services.json
    GOOGLE_SERVICES_JSON="$(cat google-services.json)" \\
        python3 tooling/scripts/firebase_android_config.py -
"""
import json
import os
import sys
from xml.sax.saxutils import escape

PACKAGE = 'com.bostrot.weft'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'apps', 'weft',
                   'android', 'app', 'src', 'main', 'res', 'values',
                   'firebase.xml')


def main(argv):
    source = argv[1] if len(argv) > 1 else '-'
    raw = os.environ.get('GOOGLE_SERVICES_JSON', '') if source == '-' \
        else open(source, encoding='utf-8').read()
    if not raw.strip():
        print('No google-services.json given; building without FCM.')
        return 0
    config = json.loads(raw)
    project = config['project_info']
    client = next(c for c in config['client']
                  if c['client_info']['android_client_info']['package_name'] == PACKAGE)
    api_key = client['api_key'][0]['current_key']
    values = {
        'google_app_id': client['client_info']['mobilesdk_app_id'],
        'gcm_defaultSenderId': project['project_number'],
        'google_api_key': api_key,
        'google_crash_reporting_api_key': api_key,
        'project_id': project['project_id'],
    }
    if project.get('storage_bucket'):
        values['google_storage_bucket'] = project['storage_bucket']
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tooling/scripts/firebase_android_config.py. '
             'Not committed. -->',
             '<resources>']
    for name, value in values.items():
        lines.append(f'    <string name="{name}" translatable="false">'
                     f'{escape(str(value))}</string>')
    lines.append('</resources>')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'Wrote the Firebase resources for project {project["project_id"]}.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
