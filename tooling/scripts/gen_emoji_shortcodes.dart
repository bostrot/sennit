// Regenerates the composer's emoji shortcode table from GitHub's gemoji.
//
// Run from the workspace root:
//
//     dart run tooling/scripts/gen_emoji_shortcodes.dart [path/to/emoji.json]
//
// Without a path it fetches `db/emoji.json` from github/gemoji's master branch.
// gemoji is the list GitHub, Slack and Discord names largely agree on —
// `:thumbsup:` and `:+1:`, `:joy:`, `:upside_down_face:` — and it is MIT
// licensed, so the table is checked in rather than pulled in as a package: a
// list of names is data, and a dependency for it would bring a picker UI and a
// font along that the app does not use.
//
// Writes `apps/weft/lib/features/chat/emoji_shortcode_data.dart`. Rerun it
// when gemoji adds a Unicode release; nothing else reads the JSON.
import 'dart:convert';
import 'dart:io';

const _source =
    'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';

const _output = 'apps/weft/lib/features/chat/emoji_shortcode_data.dart';

/// Names other clients use that gemoji does not carry, keyed by a gemoji
/// alias of the same emoji. Slack spells the thumbs with an underscore.
const Map<String, List<String>> _extraAliases = {
  '+1': ['thumbs_up'],
  '-1': ['thumbs_down'],
};

Future<void> main(List<String> args) async {
  final String raw;
  if (args.isNotEmpty) {
    raw = await File(args.first).readAsString();
  } else {
    final client = HttpClient();
    try {
      final request = await client.getUrl(Uri.parse(_source));
      final response = await request.close();
      if (response.statusCode != 200) {
        stderr.writeln('gemoji: HTTP ${response.statusCode}');
        exit(1);
      }
      raw = await response.transform(utf8.decoder).join();
    } finally {
      client.close();
    }
  }

  final entries = (jsonDecode(raw) as List).cast<Map<String, dynamic>>();
  final out = StringBuffer()
    ..writeln('// GENERATED by tooling/scripts/gen_emoji_shortcodes.dart from')
    ..writeln('// github/gemoji (MIT, Copyright (c) 2019 GitHub, Inc.).')
    ..writeln('// Do not edit by hand; rerun the script.')
    ..writeln()
    ..writeln('/// One emoji and the `:shortcode:` names it answers to.')
    ..writeln('class EmojiShortcode {')
    ..writeln(
      '  const EmojiShortcode(this.emoji, this.names, {this.tones = false});',
    )
    ..writeln()
    ..writeln('  final String emoji;')
    ..writeln()
    ..writeln('  /// Its names, the canonical one first.')
    ..writeln('  final List<String> names;')
    ..writeln()
    ..writeln('  /// Whether it takes a skin-tone modifier.')
    ..writeln('  final bool tones;')
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Every emoji with a shortcode, in gemoji\'s (Unicode\'s) order.',
    )
    ..writeln('const List<EmojiShortcode> kEmojiShortcodes = [');
  var count = 0;
  for (final entry in entries) {
    final aliases = (entry['aliases'] as List).cast<String>();
    if (aliases.isEmpty) continue;
    final names = [
      ...aliases,
      for (final alias in aliases) ...?_extraAliases[alias],
    ];
    final emoji = entry['emoji'] as String;
    final tones = entry['skin_tones'] == true;
    final quoted = names.map((n) => "'${_escape(n)}'").join(', ');
    out.writeln(
      "  EmojiShortcode('${_escape(emoji)}', [$quoted]"
      '${tones ? ', tones: true' : ''}),',
    );
    count++;
  }
  out.writeln('];');
  await File(_output).writeAsString(out.toString());
  stdout.writeln('Wrote $count emoji to $_output');
}

String _escape(String s) => s.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
