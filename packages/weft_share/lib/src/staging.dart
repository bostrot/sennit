/// How long a staged share is worth opening.
///
/// An iOS Share Extension can capture a share the user then never follows up
/// on — they share, the host app is not launched, and the container keeps the
/// files. Draining that three days later opens a compose sheet for something
/// nobody remembers choosing, on top of whatever they were actually doing. A
/// day is long enough to cover a share made at night and opened at breakfast,
/// and short enough that anything older is a surprise rather than a
/// continuation.
const Duration kStagedShareTtl = Duration(hours: 24);

/// Version stamped into every staged blob.
///
/// Present for diagnosis, not for gating: the extension ships *inside* the app
/// bundle, so a reader older than its writer cannot exist. The only skew
/// possible is a share staged before an app update and drained after one, which
/// is a new reader on an old blob — handled by the decoder's tolerance, not by
/// a version check.
const int kStagedShareFormatVersion = 1;

/// One file an extension copied into the shared container.
///
/// [relativePath] is relative to the App Group container root, never absolute.
/// The container's own URL differs between the extension and the host app
/// process on iOS, and an absolute path written by one is not a path the other
/// can open.
@immutable
class StagedFile {
  const StagedFile({
    required this.relativePath,
    required this.name,
    required this.mimeType,
    required this.sizeBytes,
  });

  final String relativePath;

  /// Display name including extension, as the provider gave it.
  final String name;

  /// What the extension believed the file to be. Re-sniffed from the bytes on
  /// ingestion — this is a hint, and an extension has less to go on than the
  /// host app does.
  final String mimeType;

  final int sizeBytes;

  ShareItem toItem() => ShareItem(
    mimeType: mimeType,
    sizeBytes: sizeBytes,
    filename: name,
  );

  Map<String, Object?> toJson() => {
    'path': relativePath,
    'name': name,
    'mimeType': mimeType,
    'sizeBytes': sizeBytes,
  };

  /// Reads a file entry back, or null when it is not a usable one.
  static StagedFile? fromJson(Object? raw) {
    if (raw is! Map) return null;
    final path = raw['path'];
    if (path is! String || path.isEmpty) return null;

    final name = raw['name'];
    final mimeType = raw['mimeType'];
    final sizeBytes = raw['sizeBytes'];
    return StagedFile(
      relativePath: path,
      name: name is String && name.isNotEmpty ? name : _basename(path),
      mimeType: mimeType is String && mimeType.isNotEmpty
          ? mimeType
          : kFallbackStagedMimeType,
      // Negative and non-numeric both mean "the extension did not know", and
      // both must read as zero rather than as a size that fails a comparison.
      sizeBytes: sizeBytes is int && sizeBytes > 0 ? sizeBytes : 0,
    );
  }

  static String _basename(String path) {
    final cut = path.lastIndexOf('/');
    return cut >= 0 ? path.substring(cut + 1) : path;
  }

  @override
  bool operator ==(Object other) =>
      other is StagedFile &&
      other.relativePath == relativePath &&
      other.name == name &&
      other.mimeType == mimeType &&
      other.sizeBytes == sizeBytes;

  @override
  int get hashCode => Object.hash(relativePath, name, mimeType, sizeBytes);

  @override
  String toString() => 'StagedFile($relativePath, $sizeBytes bytes)';
}

/// The type a staged file falls back to when the extension named none.
const String kFallbackStagedMimeType = 'application/octet-stream';

/// A share captured before the app was running.
///
/// This is the whole of what an iOS Share Extension can do. An extension has no
/// Matrix session — it cannot, the session lives in the host app's keychain and
/// its sync loop in the host app's process — and it runs under a memory ceiling
/// low enough that decrypting a room would kill it. So it copies the bytes into
/// the App Group container, writes one of these beside them, and completes. The
/// host app drains it on next launch or resume, and the send happens there.
@immutable
class StagedShare {
  const StagedShare({
    required this.id,
    required this.capturedAt,
    this.text,
    this.files = const [],
    this.targetChatId,
    this.extras = const {},
  });

  /// Unique per capture, generated by the extension.
  ///
  /// The drain is idempotent on this: a host app killed after sending but
  /// before deleting the blob must not send it twice on the next resume, and
  /// "have I already handled this one" is only answerable against an id that
  /// the extension, not the reader, decided.
  final String id;

  /// When the extension captured it, in UTC.
  final DateTime capturedAt;

  /// Accompanying text — a URL, a selection, a caption typed in the extension.
  final String? text;

  final List<StagedFile> files;

  /// The chat the user picked in the extension's own picker, if they did.
  ///
  /// Null is the normal case and means "ask in the app". It is the same field
  /// an Android Direct Share intent fills from `EXTRA_SHORTCUT_ID`, resolved to
  /// a [ShareTargetSlot.chatId], so both platforms hand the share sheet the
  /// same instruction.
  final String? targetChatId;

  /// Top-level keys the reader did not recognise, carried through re-encoding.
  ///
  /// A blob written by a newer build and read by an older one loses nothing it
  /// did not already lose; more usefully, a reader that stages a share back to
  /// disk — the drain does, when ingestion fails partway — does not silently
  /// strip fields it never understood.
  final Map<String, Object?> extras;

  /// Nothing to send. A staged share that decodes to this is dropped.
  bool get isEmpty =>
      (text == null || text!.trim().isEmpty) && files.isEmpty;

  /// Whether this is past [ttl] as of [now].
  bool isExpiredAt(DateTime now, {Duration ttl = kStagedShareTtl}) =>
      now.toUtc().difference(capturedAt.toUtc()) > ttl;

  /// This share as the ranker and the sheet see it.
  ShareContent get content => ShareContent(
    text: text,
    items: [for (final file in files) file.toItem()],
  );

  Map<String, Object?> toJson() => {
    ...extras,
    'version': kStagedShareFormatVersion,
    'id': id,
    'capturedAt': capturedAt.toUtc().toIso8601String(),
    if (text != null) 'text': text,
    if (targetChatId != null) 'targetChatId': targetChatId,
    'files': [for (final file in files) file.toJson()],
  };

  @override
  bool operator ==(Object other) =>
      other is StagedShare &&
      other.id == id &&
      other.capturedAt.isAtSameMomentAs(capturedAt) &&
      other.text == text &&
      other.targetChatId == targetChatId &&
      const ListEquality<StagedFile>().equals(other.files, files) &&
      const MapEquality<String, Object?>().equals(other.extras, extras);

  @override
  int get hashCode => Object.hash(
    id,
    capturedAt.toUtc(),
    text,
    targetChatId,
    const ListEquality<StagedFile>().hash(files),
    const MapEquality<String, Object?>().hash(extras),
  );

  @override
  String toString() =>
      'StagedShare($id, ${files.length} files, captured $capturedAt)';
}

/// Reads and writes [StagedShare] and [ShareTargetSlot] JSON for the App Group
/// container.
///
/// **Every decode is total.** Not as a nicety: the writer is a process the
/// system can kill at any instant, including between the first byte of the file
/// and the last, and the reader runs on the host app's launch path. A decoder
/// that throws on a truncated blob turns a share the user has already forgotten
/// about into an app that will not start — and will not start again, because
/// the blob that killed it is still there. So a share that cannot be read is
/// dropped, and dropping is the *documented* behaviour rather than a
/// consequence of a `try` somewhere. The caller deletes what [decode] refused.
///
/// The key names below are a cross-language contract: `ShareViewController.swift`
/// writes this JSON by hand, with no Dart on the other side of it. Renaming a
/// key here is a silent break there.
@immutable
class ShareStagingCodec {
  const ShareStagingCodec();

  /// Keys [StagedShare] owns. Anything else in the object becomes
  /// [StagedShare.extras].
  static const Set<String> _knownKeys = {
    'version',
    'id',
    'capturedAt',
    'text',
    'targetChatId',
    'files',
  };

  String encode(StagedShare share) => jsonEncode(share.toJson());

  /// [raw], or null when it is not a usable staged share.
  ///
  /// Refused, in every case without throwing:
  ///
  /// * null, empty or blank input — an extension killed before its first write;
  /// * anything `jsonDecode` cannot parse, which is what a write killed partway
  ///   through looks like;
  /// * a root that is not a JSON object;
  /// * a missing or empty `id`, since the drain cannot be idempotent without one;
  /// * a missing or unparseable `capturedAt`, since expiry cannot be judged
  ///   without one, and a share that can never expire is worse than one lost;
  /// * a share with neither text nor a usable file, which is what a blob written
  ///   before its files were copied looks like.
  StagedShare? decode(String? raw) {
    if (raw == null || raw.trim().isEmpty) return null;

    final Object? parsed;
    try {
      parsed = jsonDecode(raw);
    } on FormatException {
      return null;
    }
    if (parsed is! Map) return null;

    final id = parsed['id'];
    if (id is! String || id.isEmpty) return null;

    final capturedAt = _parseTimestamp(parsed['capturedAt']);
    if (capturedAt == null) return null;

    final text = parsed['text'];
    final targetChatId = parsed['targetChatId'];
    final files = [
      for (final file in _listOrEmpty(parsed['files']))
        ?StagedFile.fromJson(file),
    ];

    final share = StagedShare(
      id: id,
      capturedAt: capturedAt,
      text: text is String && text.trim().isNotEmpty ? text : null,
      files: files,
      targetChatId: targetChatId is String && targetChatId.isNotEmpty
          ? targetChatId
          : null,
      extras: {
        for (final entry in parsed.entries)
          if (entry.key is String && !_knownKeys.contains(entry.key))
            entry.key as String: entry.value,
      },
    );

    return share.isEmpty ? null : share;
  }

  /// Every readable share in [blobs], oldest capture first.
  ///
  /// [now] enables expiry: with it, anything past [ttl] is dropped alongside the
  /// unreadable ones, so the caller has a single "delete these" list rather than
  /// two. Oldest first because a container holding several shares holds them in
  /// the order they were made, and that is the order the user will expect to be
  /// asked about them.
  List<StagedShare> decodeAll(
    Iterable<String?> blobs, {
    DateTime? now,
    Duration ttl = kStagedShareTtl,
  }) {
    final shares = <StagedShare>[];
    for (final blob in blobs) {
      final share = decode(blob);
      if (share == null) continue;
      if (now != null && share.isExpiredAt(now, ttl: ttl)) continue;
      shares.add(share);
    }
    shares.sort((a, b) => a.capturedAt.compareTo(b.capturedAt));
    return shares;
  }

  /// The target list the host app writes for the extension's picker.
  ///
  /// Same container, same tolerance, opposite direction — here the host app is
  /// the writer and the extension the reader, and it is the *extension* that
  /// must not throw. A picker that crashes on a half-written target list takes
  /// down the share sheet of whichever app invoked it.
  String encodeTargets(List<ShareTargetSlot> slots) => jsonEncode({
    'version': kStagedShareFormatVersion,
    'targets': [for (final slot in slots) slot.toJson()],
  });

  /// The target list, or empty for anything unreadable.
  ///
  /// Empty rather than null: a missing target list means the extension shows no
  /// picker and stages without a chat id, which is exactly what it does for a
  /// user who declined to pick one. There is no error state to represent.
  List<ShareTargetSlot> decodeTargets(String? raw) {
    if (raw == null || raw.trim().isEmpty) return const [];

    final Object? parsed;
    try {
      parsed = jsonDecode(raw);
    } on FormatException {
      return const [];
    }
    if (parsed is! Map) return const [];

    return [
      for (final slot in _listOrEmpty(parsed['targets']))
        ?ShareTargetSlot.fromJson(slot),
    ];
  }

  /// [raw] as a list, or empty for anything that is not one.
  ///
  /// A cast would be shorter and would throw a [TypeError], which no `catch`
  /// above is looking for — and this runs on the host app's launch path and
  /// inside an extension that cannot show an error. The writer on the other
  /// side is hand-written Swift with no compiler checking these key names, so
  /// a `files` that arrives as a string is a skew to survive, not an
  /// impossibility.
  static List<Object?> _listOrEmpty(Object? raw) =>
      raw is List ? raw : const [];

  /// Accepts what Swift's `ISO8601DateFormatter` and Dart's
  /// `toIso8601String` both emit, plus epoch milliseconds — a number is what a
  /// hand-written Swift encoder reaches for first, and it is unambiguous.
  static DateTime? _parseTimestamp(Object? raw) {
    if (raw is int) {
      return DateTime.fromMillisecondsSinceEpoch(raw, isUtc: true);
    }
    if (raw is! String || raw.isEmpty) return null;
    return DateTime.tryParse(raw)?.toUtc();
  }
}
